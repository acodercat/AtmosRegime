"""Build the frozen train/test partition and write splits/splits.json + MANIFEST.md.

    uv run python -m atmoscoder_rl.build_splits            # refuses to clobber an existing file
    uv run python -m atmoscoder_rl.build_splits --force    # deliberate re-freeze
    uv run python -m atmoscoder_rl.build_splits --check    # verify the committed file only

The partition is the foundation every later number rests on: re-freezing it after any
training run has happened invalidates that run's comparisons. Hence --force.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter

from .datasets import index_by_id, load_core, load_splits
from .paths import SPLITS_PATH
from .splits import check_splits, make_splits

MANIFEST_PATH = SPLITS_PATH.parent / "MANIFEST.md"


def _composition(ids: list[str], core: dict) -> tuple[Counter, Counter]:
    members = [core[i] for i in ids if i in core]
    return (Counter(p.get("difficulty", "?") for p in members),
            Counter(p.get("category", "?") for p in members))


def render_manifest(splits: dict) -> str:
    core = index_by_id(load_core())
    policy = splits["policy"]
    lines = [
        "# Frozen splits",
        "",
        "Generated by `atmoscoder_rl.build_splits`. **Do not edit by hand and do not**",
        "**regenerate with a different policy** — every result in this project is",
        "conditioned on this partition.",
        "",
        f"- seed: `{splits['seed']}`",
        f"- split unit: {policy['split_unit']}",
        "- held-out books: " + ", ".join(f"*{book}*" for book in policy["held_out_books"]),
        f"- test_id fraction: {policy['test_id_fraction']:.0%}, stratified by "
        f"{' × '.join(policy['stratified_by'])}",
        "",
        "| split | role | n | what |",
        "|---|---|--:|---|",
    ]
    order = ["train", "test_id", "test_core_only", "test_book",
             "probe_trap", "probe_scaffolding", "probe_cross_domain"]
    order += [n for n in splits["splits"] if n not in order]
    for name in order:
        entry = splits["splits"][name]
        lines.append(f"| `{name}` | {entry['role']} | {entry['n']} | {entry['note']} |")

    lines += ["", "## Composition of the atmospheric splits", "",
              "| split | low | medium | high | categories |", "|---|--:|--:|--:|--:|"]
    for name in ["train", "test_id", "test_core_only", "test_book", "probe_trap"]:
        difficulty, category = _composition(splits["splits"][name]["ids"], core)
        lines.append(
            f"| `{name}` | {difficulty.get('low', 0)} | {difficulty.get('medium', 0)} "
            f"| {difficulty.get('high', 0)} | {len(category)} |"
        )

    lines += [
        "",
        "## Rules",
        "",
        "1. Only `train` (and its nested `train_*` subsets) may supply training data.",
        "   A parent's numeric and paraphrase variants inherit its split — they leak the",
        "   parent's method, so they never cross the boundary.",
        "2. `probe_*` splits are measured before and after training and are never trained on.",
        "3. Reporting accuracy on the full 436-problem core set is no longer meaningful once",
        "   training has happened. Report per-split.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="overwrite an existing splits.json")
    parser.add_argument("--check", action="store_true", help="verify the committed file, write nothing")
    args = parser.parse_args()

    if args.check:
        splits = load_splits()
    else:
        if SPLITS_PATH.exists() and not args.force:
            print(f"{SPLITS_PATH} already exists — refusing to re-freeze without --force")
            return 1
        splits = make_splits()

    failures = check_splits(splits)
    if failures:
        print("SPLIT CHECK FAILED")
        for failure in failures:
            print(f"  - {failure}")
        return 1

    for name, entry in splits["splits"].items():
        print(f"  {entry['n']:>4}  {name}")
    print("split checks passed")

    if args.check:
        return 0

    SPLITS_PATH.parent.mkdir(parents=True, exist_ok=True)
    SPLITS_PATH.write_text(json.dumps(splits, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    MANIFEST_PATH.write_text(render_manifest(splits), encoding="utf-8")
    print(f"wrote {SPLITS_PATH}\nwrote {MANIFEST_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
