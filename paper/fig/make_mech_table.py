UNIT_TEX = {"W m^-2": "W\\,m$^{-2}$", "mW/m^2": "mW\\,m$^{-2}$", "W/m^2": "W\\,m$^{-2}$", "hPa": "hPa", "MHz": "MHz", "": "",
            "nm/s": "nm\\,s$^{-1}$", "ng/s": "ng\\,s$^{-1}$", "um/s": "\\si{\\micro\\metre\\per\\second}", "nmol/L": "nmol\\,L$^{-1}$",
            "cm/s^2": "cm\\,s$^{-2}$", "m/s": "m\\,s$^{-1}$", "mm": "mm"}


def fmt(x: float) -> str:
    """Three significant figures, trailing zeros kept; thousands written out, larger magnitudes as a power of ten."""
    if x == 0:
        return "0"
    e = math.floor(math.log10(abs(x)))
    if 3 <= e < 6:
        return f"{round(x, 2 - e):,.0f}"
    if e < -3 or e >= 6:
        m = x / 10**e
        return f"{m:.2f}$\\times$10$^{{{e}}}$"
    return f"{x:.{max(0, 2 - e)}f}"


def example_cell(ex: dict) -> str:
    unit = UNIT_TEX.get(ex["unit"], ex["unit"])
    cell = f"{fmt(ex['shortcut'])} / {fmt(ex['correct'])}".replace("-", "$-$")
    return cell + (f" {unit}" if unit else "")


def main() -> None:
    rows = {r["mechanism"]: r for r in load("paper/mechanism_table.json")}
    examples = load("paper/mechanism_examples.json")["examples"]  # PREREG_PAPER_ANALYSES §23
    out = [
        "% generated by paper/fig/make_mech_table.py from results/paper/mechanism_table.json -- do not edit",
        "\\begin{table}[!ht]",
        "\\caption{\\textbf{Ten of the 72 mechanisms.} The inside and outside versions of each mechanism differ only in the triggering condition; the last column gives, for one outside problem, the value from the standard formula and the correct value. The 70 mechanisms of the training study, with base-model reachability and training outcomes, are in Supplementary Table~3.}",
        "\\label{tab:mechanisms}",
        "\\centering",
        "\\renewcommand{\\arraystretch}{1.25}\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{>{\\raggedright\\arraybackslash}p{2.3cm}>{\\raggedright\\arraybackslash}p{3.1cm}>{\\raggedright\\arraybackslash}p{3.1cm}>{\\raggedright\\arraybackslash}p{3.1cm}>{\\raggedright\\arraybackslash}p{3.0cm}}",
        "\\toprule",
        "Subfield & Standard formula & Fails when & Replacement & Example: standard / correct \\\\",
        "\\midrule",
    ]
    for name, std, fails, repl in ROWS:
        r = rows[name]
        out.append(
            f"{CATEGORY_LABEL.get(r['category'], r['category']).replace('&', '\\&')} & {std} & {fails} & {repl} & {example_cell(examples[name])} \\\\"
        )
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
